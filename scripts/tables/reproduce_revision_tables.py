#!/usr/bin/env python3
"""Recompute numerical table inputs 1, 4, 5, 6, and 7 from archived case results.

Table 2 and Table 3 are generated by scripts/figures/generate_article_outputs.py;
seed-blocked statistics are generated by analysis/statistics/verify_statistical_sensitivity.py.
Output is machine-readable CSV for verification, not manuscript LaTeX replacement.
"""
from pathlib import Path
import argparse
import pandas as pd
import numpy as np


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[2])
    ap.add_argument('--out',type=Path,default=None)
    a=ap.parse_args()
    root=a.root.resolve();results=root/'results';out=(a.out or root/'build'/'tables').resolve();out.mkdir(parents=True,exist_ok=True)
    final=pd.read_csv(results/'final'/'final_results.csv')
    assert len(final)==100 and final.state.eq('success').all()
    merged=(final.groupby(['method','lambda'],as_index=False)
           .agg(n=('relative_l2','count'),mean_l2=('relative_l2','mean'),sd_l2=('relative_l2','std'),
                mean_training_seconds=('candidate_train_seconds_total','mean'),
                sd_training_seconds=('candidate_train_seconds_total','std')))
    assert merged.n.eq(5).all()
    merged[merged.method.isin(('lra','relobralo','ddqn'))].to_csv(out/'table1_selected_adaptive_errors.csv',index=False)
    merged.to_csv(out/'table4_five_method_accuracy_cost.csv',index=False)
    stat=pd.read_csv(results/'validation_static_v1'/'production'/'summary'/'by_lambda.csv')
    assert len(stat)==4 and stat.n_seeds.eq(5).all()
    stat.to_csv(out/'table5_validation_selected_static.csv',index=False)
    ab=pd.read_csv(results/'ddqn_ablation_v1'/'production'/'summary'/'all_cases.csv')
    assert len(ab)==40
    out6=(ab.groupby(['mode','lambda'],as_index=False).agg(n=('selected_relative_l2','count'),mean_l2=('selected_relative_l2','mean'),sd_l2=('selected_relative_l2','std')))
    assert out6.n.eq(5).all()
    out6.to_csv(out/'table6_ddqn_normalization.csv',index=False)
    rows=[]
    for benchmark in ('helmholtz2d','burgers1d_time'):
        for method in ('fixed_equal','lra','relobralo','ddqn'):
            runs=sorted((results/'generalizability_v1'/'production'/benchmark/method).glob('seed_*.npz'))
            assert len(runs)==5,(benchmark,method,len(runs))
            errors=[];times=[]
            for run in runs:
                with np.load(run,allow_pickle=False) as z:
                    errors.append(float(z['selected_relative_l2']))
                    times.append(float(z['total_seconds']))
            rows.append(dict(benchmark=benchmark,method=method,n=len(runs),mean_l2=float(np.mean(errors)),
                             sd_l2=float(np.std(errors,ddof=1)),mean_five_candidate_seconds=float(np.mean(times))))
    out7=pd.DataFrame(rows)
    out7.to_csv(out/'table7_complementary_pdes.csv',index=False)
    print('REPRO_TABLES_OK:',len(merged),'5-method/parameter groups,',len(out6),'DDQN groups,',len(out7),'PDE groups')
    print(out7[['benchmark','method','mean_l2','mean_five_candidate_seconds']].to_string(index=False))

if __name__=='__main__':main()
